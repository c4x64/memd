static inline void put(__u32 *fb, __u32 w, __u32 h,
                       __u32 x, __u32 y, __u32 c)
{
    if (x < w && y < h)
        fb[y * w + x] = c;
}

void memd_raster_clear(__u32 *fb, __u32 w, __u32 h, __u32 color)
{
    __u32 i, n = w * h;
    for (i = 0; i < n; i++)
        fb[i] = color;
}

void memd_raster_rect(__u32 *fb, __u32 w, __u32 h,
                      __u32 x, __u32 y, __u32 rw, __u32 rh, __u32 color)
{
    __u32 ix, iy;
    if (!rw || !rh || x >= w || y >= h)
        return;
    if (x + rw > w)
        rw = w - x;
    if (y + rh > h)
        rh = h - y;
    for (iy = 0; iy < rh; iy++)
        for (ix = 0; ix < rw; ix++)
            fb[(y + iy) * w + (x + ix)] = color;
}

void memd_raster_line(__u32 *fb, __u32 w, __u32 h,
                      __u32 x0, __u32 y0, __u32 x1, __u32 y1, __u32 color)
{
    long dx, dy, sx, sy, err, e2, x, y;
    if (!w || !h)
        return;
    dx = (x1 > x0) ? (long)(x1 - x0) : (long)(x0 - x1);
    dy = (y1 > y0) ? (long)(y1 - y0) : (long)(y0 - y1);
    sx = (x0 < x1) ? 1 : -1;
    sy = (y0 < y1) ? 1 : -1;
    err = dx - dy;
    x = (long)x0;
    y = (long)y0;
    for (;;) {
        if (x >= 0 && y >= 0)
            put(fb, w, h, (__u32)x, (__u32)y, color);
        if (x == (long)x1 && y == (long)y1)
            break;
        e2 = 2 * err;
        if (e2 > -dy) {
            err -= dy;
            x += sx;
        }
        if (e2 < dx) {
            err += dx;
            y += sy;
        }
    }
}

void memd_raster_glyph(__u32 *fb, __u32 w, __u32 h,
                       __u32 x, __u32 y, __u32 glyph, __u32 color)
{
    unsigned row, col;
    if (glyph < 32 || glyph > 126 || x >= w || y >= h)
        return;
    for (row = 0; row < 8; row++) {
        unsigned char bits = memd_font[glyph - 32][row];
        for (col = 0; col < 8; col++) {
            if (bits & (0x80u >> col))
                put(fb, w, h, x + col, y + row, color);
        }
    }
}
